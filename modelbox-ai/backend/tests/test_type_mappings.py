def _import(dialect: str, path: Path) -> SynthesizedModel:
    result = import_ddl(path.read_bytes(), dialect, path.name)
    assert result.status == "reconciled" and result.model is not None, result.report["failures"][:3]
    return result.model


def _mapping_case(dialect: str) -> SynthesizedModel:
    stem = {"tsql": "type_mappings", "oracle": "identity", "postgres": "sequences"}[dialect]
    return _import(dialect, MAPPINGS / dialect / f"{stem}.sql")


def _export(model: SynthesizedModel, source: str, extensions: frozenset[str] = frozenset()) -> ddl_export.DdlExport:
    return ExporterService(source_dialect=source).generate_ddl_export(model, "postgres", extensions)


def _column(export: ddl_export.DdlExport, table: str, column: str) -> exp.ColumnDef:
    for statement in export.statements:
        tree = sqlglot.parse_one(statement, read="postgres")
        if isinstance(tree, exp.Create) and isinstance(tree.this, exp.Schema) and tree.this.this.name == table:
            return next(c for c in tree.this.expressions if isinstance(c, exp.ColumnDef) and c.name == column)
    raise AssertionError(f"no table {table} in the export")


def _type(export: ddl_export.DdlExport, table: str, column: str) -> str:
    return _column(export, table, column).args["kind"].sql("postgres")


def _gaps_naming(export: ddl_export.DdlExport, table: str, column: str) -> list[ddl_export.ExportGap]:
    return [g for g in export.gaps if g.entity == table and g.detail.split(" ", 1)[0].rstrip(":") == column]


# --- Plain mappings -----------------------------------------------------------------

def test_money_smallmoney_and_bit_are_exact_and_not_gaps() -> None:
    export = _export(_mapping_case("tsql"), "tsql")
    assert (_type(export, "Ledger", "Amount"), _type(export, "Ledger", "Fee")) == ("DECIMAL(19, 4)", "DECIMAL(10, 4)")
    assert (_type(export, "Ledger", "IsActive"), _type(export, "Ledger", "IsVoid")) == ("BOOLEAN", "BOOLEAN")
    defaults = [_column(export, "Ledger", c).find(exp.DefaultColumnConstraint).this.sql("postgres")
                for c in ("IsActive", "IsVoid")]
    assert defaults == ["TRUE", "FALSE"]
    for column in ("Amount", "Fee", "IsActive", "IsVoid"):
        assert _gaps_naming(export, "Ledger", column) == []


def test_a_check_over_bit_columns_compares_with_false_and_true() -> None:
    export = _export(_mapping_case("tsql"), "tsql")
    ledger = next(sqlglot.parse_one(s, read="postgres") for s in export.statements if '"Ledger"' in s[:40])
    checks = {c.this.sql("postgres") for c in ledger.find_all(exp.CheckColumnConstraint)}
    assert '"IsVoid" = FALSE OR "IsActive" = FALSE' in {re.sub(r"[()]", "", c).strip() for c in checks}


