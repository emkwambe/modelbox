# --- Every identity and sequence the file declares is emitted or named ---------------
#
# Counted from the file's own text by patterns that share nothing with the
# importer, then compared with what the export states. An importer that loses
# one (as it did before this step, silently) fails here.

_SOURCE_IDENTITY = {"tsql": re.compile(r"\bIDENTITY\s*\(", re.IGNORECASE),
                    "oracle": re.compile(r"\bAS\s+IDENTITY\b", re.IGNORECASE),
                    "postgres": re.compile(r"\bAS\s+IDENTITY\b", re.IGNORECASE)}
_SOURCE_TRIGGER_FILL = re.compile(r"\.\s*NEXTVAL\s+INTO\s+:NEW\b|:NEW\s*\.\s*\S+\s*:=\s*\S+\s*\.\s*NEXTVAL",
                                  re.IGNORECASE)
_SOURCE_SEQUENCE = re.compile(r"^\s*CREATE\s+SEQUENCE\b", re.IGNORECASE | re.MULTILINE)

CASES = [("tsql", MAPPINGS / "tsql" / "type_mappings.sql"), ("oracle", MAPPINGS / "oracle" / "identity.sql"),
         ("postgres", MAPPINGS / "postgres" / "sequences.sql"), ("oracle", GENUINE / "oracle" / "co.sql"),
         ("tsql", GENUINE / "tsql" / "adventureworks.sql"), ("postgres", GENUINE / "postgres" / "pagila.sql")]


def _stated(export: ddl_export.DdlExport) -> tuple[int, int]:
    """(identity columns stated or named, sequences created or named) in an export.

    An identity column is stated as ``GENERATED … AS IDENTITY``, or by a
    sequence default standing in for it (a gap that says so), or named: filled
    by a trigger, or not emitted for the target. A note on an emitted identity
    (ALWAYS, ON NULL) is not a second one. A sequence is created, or named;
    the stand-ins' own sequences are not the file's.
    """
    trees = [sqlglot.parse_one(s, read="postgres") for s in export.statements if not s.startswith("CREATE EXTENSION")]
    emitted = sum(1 for t in trees for _ in t.find_all(exp.GeneratedAsIdentityColumnConstraint))
    details = [g.detail for g in export.gaps if g.kind == "identity"]
    stand_ins = sum(1 for d in details if "emitted as DEFAULT nextval" in d)
    named = sum(1 for d in details if "is filled on insert by trigger" in d or ": not emitted for " in d)
    created = sum(1 for t in trees if isinstance(t, exp.Create) and str(t.args.get("kind")).upper() == "SEQUENCE")
    return emitted + stand_ins + named, created - stand_ins + sum(1 for g in export.gaps if g.kind == "sequence")


def _declared(dialect: str, path: Path) -> tuple[int, int]:
    body = path.read_text(encoding="utf-8")
    return (len(_SOURCE_IDENTITY[dialect].findall(body)) + len(_SOURCE_TRIGGER_FILL.findall(body)),
            len(_SOURCE_SEQUENCE.findall(body)))


@pytest.mark.parametrize(("dialect", "path"), CASES, ids=[p.stem for _, p in CASES])
def test_every_identity_and_sequence_is_emitted_or_named(dialect: str, path: Path) -> None:
    declared = _declared(dialect, path)
    assert sum(declared) > 0, "fixture sanity: the file declares something to count"
    export = _export(_import(dialect, path), dialect)
    assert _stated(export) == declared, (path.name, _stated(export), declared)


def test_negative_control_an_importer_that_loses_identity_fails_the_count(monkeypatch: pytest.MonkeyPatch) -> None:
    """The importer as it was before this step: every identity property dropped."""
    read_column = importer._Builder._column

    def losing_identity(self: importer._Builder, table: importer._Table, item: exp.ColumnDef,
                        statement: object) -> None:
        read_column(self, table, item, statement)  # type: ignore[arg-type]
        table.columns[item.name].identity = None

    monkeypatch.setattr(importer._Builder, "_column", losing_identity)
    path = MAPPINGS / "tsql" / "type_mappings.sql"
    assert _stated(_export(_import("tsql", path), "tsql")) != _declared("tsql", path)


def test_negative_control_an_importer_that_skips_sequences_fails_the_count(monkeypatch: pytest.MonkeyPatch) -> None:
    path = MAPPINGS / "postgres" / "sequences.sql"
    monkeypatch.setattr(importer, "_CREATE_SEQUENCE", re.compile(r"(?!)"))
    export = _export(_import("postgres", path), "postgres")
    assert _stated(export) != _declared("postgres", path)


