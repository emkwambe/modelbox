def test_a_postgresql_sequence_is_created_and_its_default_kept() -> None:
    model = _mapping_case("postgres")
    assert [s.model_dump() for s in model.sequences] == [{
        "name": "public.invoice_no_seq", "start": 1000, "increment": 5, "min_value": 1000,
        "max_value": 999999, "cache": 1, "cycle": False}]
    export = _export(model, "postgres")
    assert export.statements[0] == ("CREATE SEQUENCE public.invoice_no_seq START WITH 1000 INCREMENT BY 5 "
                                    "MINVALUE 1000 MAXVALUE 999999 CACHE 1")
    default = _column(export, "invoice", "invoice_no").find(exp.DefaultColumnConstraint)
    assert default is not None and "invoice_no_seq" in default.sql("postgres")
    assert export.gaps == []


