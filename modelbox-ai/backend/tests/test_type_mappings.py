@pytest_asyncio.fixture
async def session() -> AsyncIterator[AsyncSession]:
    engine = make_test_engine()
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
    maker = async_sessionmaker(engine, class_=AsyncSession, expire_on_commit=False)
    async with maker() as sess:
        yield sess
    await engine.dispose()


async def test_identity_and_sequences_are_stored_and_reopened(session: AsyncSession) -> None:
    model = _mapping_case("oracle")
    workspace = Workspace(name="mappings")
    session.add(workspace)
    await session.flush()
    row = DataModel(workspace_id=workspace.workspace_id, title="mappings", target_dialect="oracle",
                    current_paradigm="3NF", sequences=[s.model_dump() for s in model.sequences] or None)
    session.add(row)
    await session.flush()
    await GraphRepository(session).replace_graph(row.model_id, model.entities, model.relationships)
    await session.commit()

    # Read from outside the ORM: the stored JSON itself.
    stored = (await session.execute(text(
        "SELECT c.column_name, c.identity FROM entity_columns c JOIN model_entities e ON e.entity_id = c.entity_id "
        "WHERE e.model_id = :m AND c.identity IS NOT NULL ORDER BY c.column_name").bindparams(
            bindparam("m", type_=Uuid)), {"m": row.model_id})).all()
    assert [name for name, _ in stored] == ["ACCOUNT_ID", "NOTE_ID", "TICKET_ID"]

    reopened = await SynthesisEngine(session, None).get_model(row.model_id)  # type: ignore[arg-type]
    assert reopened is not None
    before = {(e.entity_name, c.name): c.identity for e in model.entities for c in e.columns}
    after = {(e.entity_name, c.name): c.identity for e in reopened.entities for c in e.columns}
    assert after == before
    assert reopened.sequences == model.sequences and [s.name for s in reopened.sequences] == ["APP.NOTES_SEQ"]


async def test_negative_control_a_model_saved_without_its_sequences_reopens_without_them(
    session: AsyncSession,
) -> None:
    model = _mapping_case("postgres")
    workspace = Workspace(name=f"w{uuid.uuid4().hex[:6]}")
    session.add(workspace)
    await session.flush()
    row = DataModel(workspace_id=workspace.workspace_id, title="no sequences", target_dialect="postgres",
                    current_paradigm="3NF")
    session.add(row)
    await session.flush()
    await GraphRepository(session).replace_graph(row.model_id, model.entities, model.relationships)
    await session.commit()
    reopened = await SynthesisEngine(session, None).get_model(row.model_id)  # type: ignore[arg-type]
    assert reopened is not None and reopened.sequences == [] and model.sequences
