"""Type, identity and sequence mappings to PostgreSQL (Sprint 9 Step 1a).

The decisions are SYNTHESIS P1-A's, and the owner's (2026-09-30):

* ``money`` → ``NUMERIC(19, 4)``, ``smallmoney`` → ``NUMERIC(10, 4)``, and
  ``bit`` → ``BOOLEAN``, with 0 and 1 in its defaults and CHECKs written FALSE
  and TRUE. Each is exact, so none is a gap;
* ``hierarchyid`` → ``LTREE`` and ``geography`` → PostGIS ``GEOGRAPHY``, only
  when the export says the target has the extension, and the file then starts
  with ``CREATE EXTENSION IF NOT EXISTS``. Otherwise each is a named gap;
* an identity column keeps its seed and increment, as ``GENERATED BY DEFAULT
  AS IDENTITY`` on an integer type and as a sequence default (named) on any
  other; a column an Oracle trigger fills from a sequence is a named gap;
* a PostgreSQL model's sequences are created, and its ``nextval`` defaults
  kept.

These assert what the export says, parsed back into a tree. What PostgreSQL
does with it is ``test_type_mappings_on_postgres``. Negative controls: removing
a mapping makes the column a named gap, never a silent TEXT; an importer that
loses identity columns or sequences fails the independent count below.
"""

