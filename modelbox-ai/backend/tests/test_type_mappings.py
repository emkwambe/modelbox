# --- Identity columns ---------------------------------------------------------------

def _identity(export: ddl_export.DdlExport, table: str, column: str) -> tuple[bool, int, int] | None:
    found = _column(export, table, column).find(exp.GeneratedAsIdentityColumnConstraint)
    if found is None:
        return None
    return bool(found.this), int(found.args["start"].name), int(found.args["increment"].name)


def test_sql_server_identity_keeps_its_seed_and_increment_by_default() -> None:
    export = _export(_mapping_case("tsql"), "tsql")
    assert _identity(export, "Ledger", "LedgerID") == (False, 100000, 5)
    assert _identity(export, "Batch", "BatchID") == (False, 1, 1)
    assert _gaps_naming(export, "Ledger", "LedgerID") == []


def test_oracle_identity_on_an_integer_is_by_default_and_always_is_named() -> None:
    export = _export(_mapping_case("oracle"), "oracle")
    assert _identity(export, "TICKETS", "TICKET_ID") == (False, 7, 3)
    [gap] = _gaps_naming(export, "TICKETS", "TICKET_ID")
    assert gap.kind == "identity" and "GENERATED ALWAYS" in gap.detail


def test_oracle_identity_on_number_is_a_named_sequence_default_with_its_seed() -> None:
    export = _export(_mapping_case("oracle"), "oracle")
    column = _column(export, "ACCOUNTS", "ACCOUNT_ID")
    assert column.find(exp.GeneratedAsIdentityColumnConstraint) is None
    default = column.find(exp.DefaultColumnConstraint).this.sql("postgres")
    assert default == "NEXTVAL('accounts_account_id_seq')"
    assert "CREATE SEQUENCE accounts_account_id_seq START WITH 393 INCREMENT BY 1" in export.statements
    assert export.statements.index("CREATE SEQUENCE accounts_account_id_seq START WITH 393 INCREMENT BY 1") < next(
        i for i, s in enumerate(export.statements) if '"ACCOUNTS"' in s[:40]), "the sequence comes before its table"
    [gap] = _gaps_naming(export, "ACCOUNTS", "ACCOUNT_ID")
    assert gap.kind == "identity" and "smallint, integer or bigint" in gap.detail and "ON NULL" in gap.detail


def test_a_column_an_oracle_trigger_fills_is_a_named_gap() -> None:
    model = _mapping_case("oracle")
    notes = next(e for e in model.entities if e.entity_name == "NOTES")
    identity = next(c for c in notes.columns if c.name == "NOTE_ID").identity
    assert identity is not None and (identity.kind, identity.trigger, identity.sequence) == (
        "trigger", "NOTES_BI", "NOTES_SEQ")
    export = _export(model, "oracle")
    [gap] = _gaps_naming(export, "NOTES", "NOTE_ID")
    assert gap.kind == "identity" and "NOTES_BI" in gap.detail and "NOTES_SEQ" in gap.detail
    assert _column(export, "NOTES", "NOTE_ID").find(exp.DefaultColumnConstraint) is None


